def parse(text: str, which: str) -> dict:
    block = re.search(rf"{which}ColorScheme\((.*?)\n\s*\)", text, re.S)
    if not block:
        raise SystemExit(f"no {which} scheme")
    values = {}
    for name, hex_value in re.findall(r"(\w+)\s*=\s*Color\(0x([0-9A-Fa-f]{8})\)", block.group(1)):
        values[name] = hex_value[2:].upper()
    return values


def scheme(values: dict, mode: str) -> str:
    merged = dict(BASELINE[mode])
    merged.update(values)
    if "surfaceTint" not in values:
        merged["surfaceTint"] = merged["primary"]
    args = ",\n".join(f"            {role}: 0x{merged[role]}" for role in ROLES)
    return f"M3ColorScheme(\n{args}\n        )"


def main() -> None:
    lines = [
        "// Generated by ios/scripts/generate-themes.py from the Android app's colour schemes. Don't edit.",
        "",
        "/// The built-in themes (Android's `AppTheme`, without Monet and the user's own themes).",
        "enum AppTheme: String, CaseIterable, Identifiable, Sendable {",
    ]
    lines += [f"    case `{case}`" if case == "default" else f"    case {case}" for case, _, _ in THEMES]
    lines += ["", "    var id: Self { self }", "", "    var title: String {", "        switch self {"]
    lines += [f'        case .{case}: String(localized: "{title}")' for case, _, title in THEMES]
    lines += ["        }", "    }", "", "    var light: M3ColorScheme {", "        switch self {"]
    lines += [f"        case .{case}: .{case}Light" for case, _, _ in THEMES]
    lines += ["        }", "    }", "", "    var dark: M3ColorScheme {", "        switch self {"]
    lines += [f"        case .{case}: .{case}Dark" for case, _, _ in THEMES]
    lines += ["        }", "    }", "}", "", "extension M3ColorScheme {"]
    for case, file, _ in THEMES:
        text = (SRC / file).read_text()
        for mode in ("dark", "light"):
            lines.append(f"    static let {case}{mode.capitalize()} = {scheme(parse(text, mode), mode)}")
            lines.append("")
    lines[-1] = "}"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(THEMES)} themes written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
